// Writes src/lib/generated-logo-metrics.ts: Nunito's advance widths, read from the very font files the
// offline renderer ships (renderer/fonts), so the generated logo is sized by arithmetic rather than by
// measuring text in a browser. Arithmetic gives the same size on the server, in the share page and in
// the app's offline WebView — a measured size would not (decision 0181).
//
//   node scripts/gen-generated-logo-metrics.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function metrics(file) {
  const b = readFileSync(join(root, "renderer/fonts", file));
  const u16 = (o) => b.readUInt16BE(o), i16 = (o) => b.readInt16BE(o), u32 = (o) => b.readUInt32BE(o);
  const tables = {};
  for (let i = 0, n = u16(4); i < n; i++) {
    const r = 12 + i * 16;
    tables[b.toString("latin1", r, r + 4)] = u32(r + 8);
  }
  const unitsPerEm = u16(tables.head + 18);
  const ascender = i16(tables.hhea + 4), descender = i16(tables.hhea + 6), lineGap = i16(tables.hhea + 8);
  const numberOfHMetrics = u16(tables.hhea + 34);
  const advance = (g) => u16(tables.hmtx + 4 * Math.min(g, numberOfHMetrics - 1));
  // cmap: the Windows Unicode BMP subtable, format 4.
  let sub = -1;
  for (let i = 0, n = u16(tables.cmap + 2); i < n; i++) {
    const r = tables.cmap + 4 + i * 8;
    if (u16(r) === 3 && u16(r + 2) === 1) sub = tables.cmap + u32(r + 4);
  }
  if (sub < 0 || u16(sub) !== 4) throw new Error(`${file}: no format-4 cmap`);
  const segX2 = u16(sub + 6), ends = sub + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2;
  const glyph = (c) => {
    for (let s = 0; s < segX2 / 2; s++) {
      if (c > u16(ends + 2 * s)) continue;
      if (c < u16(starts + 2 * s)) return 0;
      const ro = u16(ranges + 2 * s);
      if (ro === 0) return (c + i16(deltas + 2 * s)) & 0xffff;
      const g = u16(ranges + 2 * s + ro + 2 * (c - u16(starts + 2 * s)));
      return g === 0 ? 0 : (g + i16(deltas + 2 * s)) & 0xffff;
    }
    return 0;
  };
  const widths = {};
  let widest = 0;
  for (let c = 32; c <= 0x17f; c++) {
    const g = glyph(c);
    if (!g) continue;
    const w = Math.round((advance(g) / unitsPerEm) * 1000);
    widths[String.fromCharCode(c)] = w;
    widest = Math.max(widest, w);
  }
  return {
    widths,
    // A character the table does not hold is taken as wide as the widest one it does: a guess that can
    // only make the text smaller, never push it out of the circle.
    fallback: widest,
    lineHeight: Math.round(((ascender - descender + lineGap) / unitsPerEm) * 1000),
    ascent: Math.round((ascender / unitsPerEm) * 1000),
  };
}

const extraBold = metrics("nunito_extra_bold.ttf");
const bold = metrics("nunito_bold.ttf");
const out = `// GENERATED by scripts/gen-generated-logo-metrics.mjs from renderer/fonts — do not edit by hand.
// Nunito advance widths in thousandths of an em, for sizing the generated logo's text (decision 0181).
export interface FontMetrics { widths: Record<string, number>; fallback: number; lineHeight: number; ascent: number }
export const NUNITO_EXTRA_BOLD: FontMetrics = ${JSON.stringify(extraBold)};
export const NUNITO_BOLD: FontMetrics = ${JSON.stringify(bold)};
`;
writeFileSync(join(root, "src/lib/generated-logo-metrics.ts"), out);
console.log("wrote src/lib/generated-logo-metrics.ts", Object.keys(extraBold.widths).length, "chars", extraBold.lineHeight, extraBold.ascent);
